<?php
/**
 * Regenerates docs/tools-list.md: every MCP tool with its read/write flag and description.
 *
 * Usage (repo root):  php bin/generate-tools-list.php
 *
 * Loads the plugin's real registration code (registry.php, tools/native-tools.php,
 * tools/admin-tool-defs.php) against minimal WordPress stubs, with every integration
 * (WooCommerce, Elementor, ACF, Yoast, Rank Math, UAE, Gravity Forms, CF7, WPForms)
 * forced "active" so the list is the complete set. Not shipped with the plugin.
 *
 * If it fatals on an undefined function after you added a tool, add a stub below.
 */

error_reporting( E_ALL & ~E_DEPRECATED );

$root     = dirname( __DIR__ );
$includes = $root . '/wsp-mcp-ai-agents-connector/includes';
$out      = $root . '/docs/tools-list.md';

define( 'ABSPATH', '/stub/' );
define( 'WSP_MCP_VERSION', '0' );

foreach ( array( 'WooCommerce', 'ACF', 'GFAPI', 'WPCF7_ContactForm', 'WPForms' ) as $c ) {
	eval( "class $c {}" );
}
foreach ( array( 'wsp_yoast_is_active', 'wsp_rankmath_is_active', 'wsp_elementor_is_active', 'wsp_acf_is_active', 'wsp_uae_is_active', 'wsp_gravity_is_active', 'wsp_cf7_is_active', 'wsp_wpforms_is_active' ) as $f ) {
	eval( "function $f() { return true; }" );
}
function __( $s ) { return $s; }
function esc_html__( $s ) { return $s; }
function add_action() {}
function add_filter() {}
function do_action() {}
function apply_filters( $t, $v ) { return $v; }
function get_option( $k, $d = false ) { return $d; }

class WSP_MCP_Server {
	public static $tools = array();
	public static function register_tool( $name, $spec ) { self::$tools[ $name ] = $spec; }
}

require $includes . '/registry.php';
require $includes . '/tools/admin-tool-defs.php';
require $includes . '/tools/native-tools.php';

wsp_mcp_register_native_tools();

$registry = wsp_mcp_ability_registry();
$groups   = array();
foreach ( WSP_MCP_Server::$tools as $name => $spec ) {
	$meta = $registry[ $spec['enable_key'] ] ?? null;
	$groups[ $meta['group'] ?? 'Site Context' ][] = array( $name, $meta['access'] ?? 'read', $spec['description'] );
}
ksort( $groups );

$total = count( WSP_MCP_Server::$tools );
$md    = "# WSP MCP — all tools ($total, every integration active)\n\n"
	. "> Generated by `php bin/generate-tools-list.php` — do not edit by hand. Regenerated automatically when a tool is added (see AGENTS.md).\n\n";
foreach ( $groups as $g => $rows ) {
	$md .= "## $g (" . count( $rows ) . ")\n\n| Tool | R/W | Description |\n|---|---|---|\n";
	foreach ( $rows as $r ) {
		$md .= '| `' . $r[0] . '` | ' . $r[1] . ' | ' . str_replace( array( '|', "\n" ), array( '\\|', ' ' ), $r[2] ) . " |\n";
	}
	$md .= "\n";
}
file_put_contents( $out, $md );
echo "Wrote $out — $total tools\n";
